/**
 * Syncs the desktop icon set (crates/ui/assets/icons — Solar Icons Linear,
 * CC BY 4.0, plus Cosmos's own marks) into src/lib/solar-icons.ts so the
 * mobile app renders the exact same glyphs via react-native-svg's SvgXml.
 *
 * Run: node scripts/sync-icons.mjs   (from apps/mobile)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '../../../crates/ui/assets/icons');
const out = join(here, '../src/lib/solar-icons.ts');

const files = readdirSync(src).filter((f) => f.endsWith('.svg')).sort();
const entries = files.map((f) => {
  const name = f.replace(/\.svg$/, '');
  // Normalize to a single line so the template literal stays one line per icon.
  const xml = readFileSync(join(src, f), 'utf8').replace(/>\s+</g, '><').trim();
  if (xml.includes('`') || xml.includes('${')) throw new Error(`${f}: unsafe for template literal`);
  return `  '${name}': \`${xml}\`,`;
});

const header = `/**
 * GENERATED by scripts/sync-icons.mjs — do not edit by hand.
 * Solar Icons (Linear weight) by 480 Design, CC BY 4.0 — the same SVG assets
 * the desktop app embeds from crates/ui/assets/icons, plus Cosmos's own marks.
 * Every glyph draws with stroke="currentColor" / fill="currentColor", so pass
 * the tint via SvgXml's \`color\` prop.
 */
export const SOLAR_ICONS: Record<string, string> = {
`;

writeFileSync(out, header + entries.join('\n') + '\n};\n');
console.log(`wrote ${entries.length} icons → ${out}`);
